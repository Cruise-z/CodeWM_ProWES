"""Tests for the 2048 game implementation."""

from Main import run_demo
from twenty48.move import move_line_left
from twenty48.types import Direction, GameStatus


def test_move_line_left_fixtures():
    """Test the canonical move_line_left function with various inputs."""
    # Test case 1: No merge needed
    result, score = move_line_left([2, 4, 8, 16])
    assert result == [2, 4, 8, 16]
    assert score == 0

    # Test case 2: Single merge
    result, score = move_line_left([2, 2, 4, 8])
    assert result == [4, 4, 8, 0]
    assert score == 4

    # Test case 3: Multiple merges
    result, score = move_line_left([2, 2, 2, 2])
    assert result == [4, 4, 0, 0]
    assert score == 8

    # Test case 4: Merge with gaps
    result, score = move_line_left([4, 0, 4, 0])
    assert result == [8, 0, 0, 0]
    assert score == 8

    # Test case 5: Merge and shift
    result, score = move_line_left([0, 0, 2, 2])
    assert result == [4, 0, 0, 0]
    assert score == 4

    # Test case 6: Padding to length 4
    result, score = move_line_left([2, 2])
    assert result == [4, 0, 0, 0]
    assert score == 4

    # Test case 7: All zeros
    result, score = move_line_left([0, 0, 0, 0])
    assert result == [0, 0, 0, 0]
    assert score == 0

    # Test case 8: Single element
    result, score = move_line_left([4])
    assert result == [4, 0, 0, 0]
    assert score == 0

    # Test case 9: Skip after merge (consecutive equal elements)
    result, score = move_line_left([2, 2, 4, 4])
    assert result == [4, 4, 4, 0]
    assert score == 8

    # Test case 10: Complex merge pattern
    result, score = move_line_left([8, 4, 4, 2])
    assert result == [8, 8, 2, 0]
    assert score == 8

    # Test case 11: No merge at all
    result, score = move_line_left([2, 4, 8, 16])
    assert result == [2, 4, 8, 16]
    assert score == 0

    # Test case 12: Zero-padding with non-zero elements
    result, score = move_line_left([0, 2, 0, 4])
    assert result == [2, 4, 0, 0]
    assert score == 0


def test_run_demo_smoke():
    """Smoke test for run_demo function with seed 0."""
    # Call run_demo with seed 0
    status, score, tiles_count = run_demo(0)
    
    # Validate return types
    assert isinstance(status, GameStatus)
    assert isinstance(score, int)
    assert isinstance(tiles_count, int)
    
    # Validate deterministic behavior
    status1, score1, tiles_count1 = run_demo(0)
    assert status == status1
    assert score == score1
    assert tiles_count == tiles_count1
    
    # Validate expected values for seed 0
    # With seed 0, the initial board will have two tiles placed at random positions
    # The exact values depend on the random sequence generated by seed 0
    # But we know the game should be in RUNNING state, score > 0, and tiles_count > 0
    assert status == GameStatus.RUNNING or status == GameStatus.WON or status == GameStatus.LOST
    assert score >= 0
    assert tiles_count >= 0
    assert tiles_count <= 16  # Maximum possible tiles on a 4x4 board